/**
 * i18n/<locale>/ → addon/Keyring/Text_<locale>.lua, one for every language the
 * game has (a stub where there is no translation yet, so the TOC never names
 * a missing file): each client loads its own, through Text_[TextLocale].lua in
 * the TOCs, and English stays wherever a translation says nothing (Core.lua).
 *
 *   i18n/<locale>/meta.json    { "flagged": true }  (a first translation, not
 *                              reviewed by a native reader)
 *   i18n/<locale>/words.json   { "English": "translation" }: every L["..."] of
 *                              the addon; i18n/words.json lists them
 *
 * A language not given its own folder may borrow another's (esMX: esES).
 *
 *   bun scripts/locales.ts            write the Text files
 *   bun scripts/locales.ts --check    fail if one isn't up to date or a word
 *                                     has no translation; say what is unused
 *   bun scripts/locales.ts --keys     write i18n/words.json, every word to translate
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const I18N = join(ROOT, "i18n");
const ADDON = join(ROOT, "addon/Keyring");
const LOCALES = ["enUS", "enGB", "deDE", "frFR", "esES", "esMX", "ruRU", "ptBR", "itIT", "koKR", "zhCN", "zhTW"];
const ENGLISH = new Set(["enUS", "enGB"]);
const BORROWS: Record<string, string> = { esMX: "esES" };

// every L["..."] of the addon's own files
function keys(): string[] {
  const found = new Set<string>();
  for (const f of readdirSync(ADDON).sort()) {
    if (!f.endsWith(".lua") || f.startsWith("Text_")) continue;
    const src = readFileSync(join(ADDON, f), "utf8");
    for (const m of src.matchAll(/\bL\["((?:[^"\\]|\\.)*)"\]/g)) found.add(m[1].replace(/\\"/g, '"').replace(/\\n/g, "\n"));
  }
  return [...found].sort();
}

const q = (s: string) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")}"`;
const json = (file: string) => (existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : {});

function luaFor(locale: string): string {
  const from = BORROWS[locale] && !existsSync(join(I18N, locale)) ? BORROWS[locale] : locale;
  const lines = [`-- Generated by scripts/locales.ts from i18n/${from}/: edit those, not this file.`];
  if (ENGLISH.has(locale) || !existsSync(join(I18N, from))) {
    lines.push(`-- (${ENGLISH.has(locale) ? "English: the words as the addon writes them" : "no translation yet: English"})`);
    return `${lines.join("\n")}\n`;
  }
  const words: Record<string, string> = json(join(I18N, from, "words.json"));
  lines.push("local _, ns = ...", "ns.translate({", "  words = {");
  for (const [k, v] of Object.entries(words)
    .filter(([, v]) => v)
    .sort(([a], [b]) => a.localeCompare(b)))
    lines.push(`    [${q(k)}] = ${q(v)},`);
  lines.push("  },", "})");
  return `${lines.join("\n")}\n`;
}

const args = process.argv.slice(2);
const all = keys();
if (args[0] === "--keys") {
  writeFileSync(join(I18N, "words.json"), `${JSON.stringify(Object.fromEntries(all.map((k) => [k, ""])), null, 2)}\n`);
  console.log(`✓ i18n/words.json: ${all.length} words to translate`);
  process.exit(0);
}
const check = args.includes("--check");
let bad = false;
for (const locale of LOCALES) {
  const out = join(ADDON, `Text_${locale}.lua`);
  const lua = luaFor(locale);
  if (check) {
    if ((existsSync(out) ? readFileSync(out, "utf8") : "") !== lua) {
      console.error(`✗ ${relative(ROOT, out)} is out of date: run bun scripts/locales.ts`);
      bad = true;
    }
  } else writeFileSync(out, lua);
  if (!existsSync(join(I18N, locale))) continue;
  const words: Record<string, string> = json(join(I18N, locale, "words.json"));
  const meta = json(join(I18N, locale, "meta.json"));
  const missing = all.filter((k) => !words[k]);
  const unused = Object.keys(words).filter((k) => !all.includes(k));
  console.log(`${locale}: ${all.length - missing.length}/${all.length} words${meta.flagged ? ", flagged" : ""}`);
  if (missing.length) {
    console.error(`  ✗ no translation: ${missing.join(" | ")}`);
    if (check) bad = true;
  }
  if (unused.length) console.log(`  words no longer used: ${unused.join(" | ")}`);
  // (no semicolons in what players read, in any language: two sentences, or a comma)
  for (const [k, v] of Object.entries(words))
    if (v.includes(";")) {
      console.error(`  ✗ a semicolon: ${v}`);
      bad = true;
    }
}
for (const k of all)
  if (k.includes(";")) {
    console.error(`✗ a semicolon: ${k}`);
    bad = true;
  }
if (bad) process.exit(1);
